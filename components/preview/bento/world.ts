function inside([x, y]: [number, number], poly: Poly) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

export const VIEW = { lon0: -128, lon1: 168, lat0: -46, lat1: 74, scale: 2 };
export const W = (VIEW.lon1 - VIEW.lon0) * VIEW.scale;
export const H = (VIEW.lat1 - VIEW.lat0) * VIEW.scale;

export function project(lon: number, lat: number): [number, number] {
  return [(lon - VIEW.lon0) * VIEW.scale, (VIEW.lat1 - lat) * VIEW.scale];
}

const STEP = 3.6;

export type Dot = { x: number; y: number; home: boolean };

export const dots: Dot[] = (() => {
  const out: Dot[] = [];
  let row = 0;
  for (let lat = VIEW.lat1 - STEP / 2; lat > VIEW.lat0; lat -= STEP, row++) {
    const shift = row % 2 ? STEP / 2 : 0;
    for (let lon = VIEW.lon0 + STEP / 2 + shift; lon < VIEW.lon1; lon += STEP) {
      const p: [number, number] = [lon, lat];
      const home = inside(p, india);
      if (home || land.some((poly) => inside(p, poly))) {
        const [x, y] = project(lon, lat);
        out.push({ x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10, home });
      }
    }
  }
  return out;
})();
